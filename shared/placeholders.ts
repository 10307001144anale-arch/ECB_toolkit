// Placeholder parsing, matching and substitution shared by the client editor,
// validation, the PDF renderer and the server.
//
// Standard syntax:     {{field_name}}
// Alternative syntax:  (field_name)  — only recognised for registered names,
//                      so ordinary text in brackets is never replaced.

export const PLACEHOLDER_NAME = '[A-Za-z][A-Za-z0-9_]{0,63}';
const CURLY_RE = new RegExp(`\\{\\{\\s*(${PLACEHOLDER_NAME})\\s*\\}\\}`, 'g');
const PAREN_RE = new RegExp(`\\((${PLACEHOLDER_NAME})\\)`, 'g');
/** Detects anything that looks like an attempted placeholder but is malformed, e.g. {{ }} or {{first name}}. */
const MALFORMED_RE = /\{\{([^{}]*)\}\}/g;

/** Values generated by the system rather than read from the spreadsheet. */
export const SYSTEM_PLACEHOLDERS: Record<string, { label: string; description: string }> = {
  certificateid: { label: 'Certificate ID', description: 'Unique ID issued for each certificate (used for verification).' },
  row: { label: 'Row number', description: 'Position of the participant in the list (1, 2, 3…).' },
  today: { label: "Today's date", description: 'The date the certificates are generated.' },
};

export interface PlaceholderToken {
  name: string; // as typed
  key: string; // normalised (lower-case)
  start: number;
  end: number;
  syntax: 'curly' | 'paren';
}

export function normKey(name: string): string {
  return name.trim().toLowerCase();
}

export function isSystemPlaceholder(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(SYSTEM_PLACEHOLDERS, normKey(name));
}

/**
 * Finds placeholders in a piece of text.
 * @param registered normalised names that may also be written as (name).
 */
export function findPlaceholders(text: string, registered?: Set<string>): PlaceholderToken[] {
  const out: PlaceholderToken[] = [];
  if (!text) return out;
  for (const m of text.matchAll(CURLY_RE)) {
    out.push({ name: m[1], key: normKey(m[1]), start: m.index!, end: m.index! + m[0].length, syntax: 'curly' });
  }
  if (registered && registered.size > 0) {
    for (const m of text.matchAll(PAREN_RE)) {
      const key = normKey(m[1]);
      if (!registered.has(key)) continue;
      const start = m.index!;
      // Skip if inside a curly token already found.
      if (out.some((t) => start >= t.start && start < t.end)) continue;
      out.push({ name: m[1], key, start, end: start + m[0].length, syntax: 'paren' });
    }
  }
  return out.sort((a, b) => a.start - b.start);
}

/** Returns malformed {{...}} fragments, e.g. "{{first name}}", so the editor can warn about them. */
export function findMalformedPlaceholders(text: string): string[] {
  const bad: string[] = [];
  if (!text) return bad;
  const valid = new RegExp(`^\\s*${PLACEHOLDER_NAME}\\s*$`);
  for (const m of text.matchAll(MALFORMED_RE)) {
    if (!valid.test(m[1])) bad.push(m[0]);
  }
  return bad;
}

/** Unique placeholder keys (normalised) used across many texts, keeping first-seen display names. */
export function collectPlaceholders(texts: string[], registered?: Set<string>): Map<string, string> {
  const map = new Map<string, string>();
  for (const t of texts) {
    for (const tok of findPlaceholders(t, registered)) {
      if (!map.has(tok.key)) map.set(tok.key, tok.name);
    }
  }
  return map;
}

/**
 * Replaces placeholders with values. Static text is preserved exactly.
 * Unknown placeholders are left untouched and reported in `missing`.
 */
export function resolvePlaceholders(
  text: string,
  values: Record<string, string>,
  registered?: Set<string>
): { text: string; missing: string[] } {
  const tokens = findPlaceholders(text, registered);
  if (tokens.length === 0) return { text: text || '', missing: [] };
  const missing: string[] = [];
  let out = '';
  let cursor = 0;
  for (const tok of tokens) {
    out += text.slice(cursor, tok.start);
    const v = values[tok.key];
    if (v === undefined || v === null || String(v).trim() === '') {
      missing.push(tok.name);
      out += text.slice(tok.start, tok.end);
    } else {
      out += String(v);
    }
    cursor = tok.end;
  }
  out += text.slice(cursor);
  return { text: out, missing };
}

/** Converts an arbitrary column header into a safe placeholder name: "Full Name" -> "full_name". */
export function columnToPlaceholder(column: string): string {
  let s = column
    .trim()
    .replace(/([a-z])([A-Z])/g, '$1_$2')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
  if (!s) s = 'field';
  if (!/^[a-z]/.test(s)) s = `f_${s}`;
  return s.slice(0, 64);
}

function squash(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/** Synonyms used for automatic column matching. Keys and values are squashed. */
const SYNONYMS: Record<string, string[]> = {
  name: ['fullname', 'participantname', 'participant', 'recipientname', 'recipient', 'studentname', 'student', 'attendee', 'attendeename', 'nameofparticipant', 'name'],
  cid: ['citizenshipid', 'cidno', 'cidnumber', 'citizenid', 'nationalid', 'idnumber', 'idno', 'cid'],
  workshop: ['programme', 'program', 'workshopname', 'event', 'eventname', 'training', 'trainingname', 'course', 'coursename', 'workshop'],
  programme: ['program', 'programme', 'programmename', 'programname', 'workshop', 'course'],
  course: ['course', 'coursename', 'coursetitle', 'subject', 'programme', 'program'],
  date: ['date', 'eventdate', 'issuedate', 'dateofissue', 'completiondate', 'trainingdate', 'workshopdate'],
  college: ['college', 'institute', 'institution', 'school', 'organisation', 'organization', 'university', 'collegename'],
  email: ['email', 'emailaddress', 'mail'],
  photo: ['photo', 'photograph', 'picture', 'image', 'photofile', 'photofilename', 'passportphoto'],
  signature: ['signature', 'signaturefile', 'sign', 'signaturefilename'],
  certificateid: ['certificateid', 'certificateno', 'certificatenumber', 'certno', 'certid', 'serialno', 'serialnumber'],
};

/**
 * Returns the best column for a placeholder name, or null.
 * Order: exact → squashed exact → synonym → containment.
 */
export function matchColumn(placeholder: string, columns: string[], taken: Set<string> = new Set()): string | null {
  const free = columns.filter((c) => !taken.has(c));
  const p = squash(placeholder);
  if (!p) return null;
  const exact = free.find((c) => c.trim().toLowerCase() === placeholder.trim().toLowerCase());
  if (exact) return exact;
  const sq = free.find((c) => squash(c) === p);
  if (sq) return sq;
  const syn = SYNONYMS[p];
  if (syn) {
    for (const s of syn) {
      const hit = free.find((c) => squash(c) === s);
      if (hit) return hit;
    }
  }
  // Reverse synonym lookup: placeholder is itself a synonym of a group.
  for (const [group, list] of Object.entries(SYNONYMS)) {
    if (list.includes(p)) {
      const hit = free.find((c) => squash(c) === group || list.includes(squash(c)));
      if (hit) return hit;
    }
  }
  if (p.length >= 3) {
    const contains = free.find((c) => {
      const cs = squash(c);
      return cs.length >= 3 && (cs.includes(p) || p.includes(cs));
    });
    if (contains) return contains;
  }
  return null;
}
